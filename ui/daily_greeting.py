class DailyGreetingService:
    """Resolve one stable greeting per calendar day with recent-repeat avoidance."""

    HISTORY_VERSION = 1
    DEFAULT_HISTORY_LIMIT = 7

    def __init__(
        self,
        greetings: Sequence[Greeting] = GREETINGS,
        *,
        history_path: str | Path | None = None,
        history_limit: int = DEFAULT_HISTORY_LIMIT,
    ) -> None:
        if not greetings:
            raise ValueError("greeting pool must not be empty")
        if history_limit < 0:
            raise ValueError("history_limit must be non-negative")

        self.greetings = tuple(greetings)
        self.history_path = (
            Path(history_path) if history_path is not None else None
        )
        self.history_limit = history_limit

    def greeting_for_date(self, day: date) -> Greeting:
        history = self._load_history()

        for entry in reversed(history):
            if (
                isinstance(entry, dict)
                and entry.get("date") == day.isoformat()
                and isinstance(entry.get("index"), int)
            ):
                return self.greetings[entry["index"]]

        index = self._stable_index(day)
        recent_indexes = {
            int(entry["index"])
            for entry in history
            if isinstance(entry, dict) and "index" in entry
        }

        if len(self.greetings) > 1 and index in recent_indexes:
            index = self._next_available_index(index, recent_indexes)

        greeting = self.greetings[index]
        self._record(day, index)
        return greeting

    def text_for_date(self, day: date) -> str:
        return self.greeting_for_date(day).text

    def today(self) -> Greeting:
        return self.greeting_for_date(date.today())

    def today_text(self) -> str:
        return self.today().text

    def _stable_index(self, day: date) -> int:
        digest = hashlib.sha256(day.isoformat().encode("utf-8")).digest()
        value = int.from_bytes(digest[:8], "big")
        return value % len(self.greetings)

    def _next_available_index(
        self,
        start: int,
        recent_indexes: set[int],
    ) -> int:
        for offset in range(1, len(self.greetings)):
            candidate = (start + offset) % len(self.greetings)
            if candidate not in recent_indexes:
                return candidate
        return start

    def _load_history(self) -> list[dict[str, object]]:
        if self.history_path is None or not self.history_path.exists():
            return []

        try:
            payload = json.loads(
                self.history_path.read_text(encoding="utf-8")
            )
        except (OSError, ValueError, TypeError):
            return []

        if not isinstance(payload, dict):
            return []

        entries = payload.get("entries", [])
        if not isinstance(entries, list):
            return []

        return [
            entry for entry in entries
            if isinstance(entry, dict)
        ][-self.history_limit:]

    def _record(self, day: date, index: int) -> None:
        if self.history_path is None or self.history_limit == 0:
            return

        history = self._load_history()

        entry = {
            "date": day.isoformat(),
            "index": index,
        }

        history = [
            item for item in history
            if item.get("date") != day.isoformat()
        ]
        history.append(entry)
        history = history[-self.history_limit:]

        self.history_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "version": self.HISTORY_VERSION,
            "entries": history,
        }
        self.history_path.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )


def greeting_history_path(
    *,
    base_directory: str | Path | None = None,
) -> Path:
    if base_directory is not None:
        base = Path(base_directory)
    else:
        import os
        base = Path(
            os.environ.get(
                "LOCALAPPDATA",
                str(Path.home() / "AppData" / "Local"),
            )
        ) / "PacePilot"

    return base / "greeting_history.json"


